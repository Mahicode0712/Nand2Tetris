// While any key is pressed, draw a black 48x20 box starting at row 42.
// When the key is released, clear the same area.

@SCREEN
D=A
@base
M=D
@42
D=A
@rowOffset
M=D

(SET_BASE)
@rowOffset
D=M
@0
D=D-A
@DRAW
D;JLE
@32
D=A
@base
M=M+D
@rowOffset
M=M-1
@SET_BASE
0;JMP

(DRAW)
@20
D=A
@rows
M=D

(ROW_LOOP)
@rows
D=M
@0
D=D-A
@CHECK_KEY
D;JLE
@base
D=M
@cursor
M=D
@3
D=A
@cols
M=D

(COL_LOOP)
@cols
D=M
@0
D=D-A
@NEXT_ROW
D;JLE
@cursor
A=M
M=-1
@cursor
M=M+1
@cols
M=M-1
@COL_LOOP
0;JMP

(NEXT_ROW)
@32
D=A
@base
M=M+D
@rows
M=M-1
@ROW_LOOP
0;JMP

(CHECK_KEY)
@KBD
D=M
@DRAW
